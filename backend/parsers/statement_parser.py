_EXPENSE_FIELDS = {"operating_expense_total", "cost_of_goods_sold", "selling_expenses", "administrative_expenses",
                   "exchange_loss", "interest_expense", "tax_expense", "capital_expenditure", "cash_interest_paid", "cash_principal_repaid"}
_NONNEGATIVE_BALANCES = {"assets", "liabilities", "current_assets", "current_liabilities", "cash_balance",
                         "opening_cash_including_restricted", "closing_cash_including_restricted"}


def _period(header: str) -> dict:
    text = _normalize(header)
    match = re.search(r"(?<!\d)(\d{4})(?!\d)", text)
    year = int(match.group(1)) if match else None
    if year is not None and year >= 2400:
        year -= 543
    end = None
    match = re.search(r"(\d{1,2})\s+([^\d\s]+)\s+(?:พ\.?\s*ศ\.?\s*)?(\d{4})", text)
    if match and match.group(2) in _MONTHS:
        date_year = int(match.group(3))
        if date_year >= 2400:
            date_year -= 543
        try:
            end = date(date_year, _MONTHS[match.group(2)], int(match.group(1))).isoformat()
        except ValueError as exc:
            raise ExtractionError("Invalid reporting date in statement header") from exc
    return {"header": header, "year": year, "periodEnd": end}


def _units(headers: list[str]) -> tuple[str | None, Decimal]:
    text = _normalize(" ".join(headers))
    usd = "ดอลลาร์" in text or "เหรียญสหรัฐ" in text or "usd" in text or "us dollars" in text
    thb = "บาท" in text or "baht" in text or "thb" in text
    if usd and thb:
        raise ExtractionError("Conflicting currencies within a statement section")
    currency = "USD" if usd else "THB" if thb else None
    scale = Decimal("1000000") if "million" in text or "ล้าน" in text else Decimal(1)
    return currency, scale


def _amount(cell, field: str, scale: Decimal) -> tuple[Decimal | None, str | None]:
    if cell.value is None or isinstance(cell.value, str) and cell.value.strip() in {"", "-", "–", "—"}:
        return None, None
    try:
        raw = _MONEY.validate_python(_cell_value("net_income", cell.value))
    except (ValueError, ValidationError) as exc:
        raise ExtractionError(f"Cell {cell.coordinate}: invalid monetary value") from exc
    value = raw * scale
    if field in _EXPENSE_FIELDS:
        value = abs(value)
    if field == "financing_cash_flow":
        value = -abs(value)
    if field in _NONNEGATIVE_BALANCES and value < 0:
        raise ExtractionError(f"Cell {cell.coordinate}: negative balance is not allowed")
    return value, format(raw, "f")


def _check(checks: list, name: str, actual: Decimal | None, expected: Decimal | None) -> None:
    difference = None if actual is None or expected is None else actual - expected
    checks.append({"id": name, "status": "insufficient_data" if difference is None else
                   "ok" if abs(difference) <= _TOLERANCE else "mismatch",
                   "difference": None if difference is None else format(difference, "f")})


def _sum_fields(fields: dict, names: tuple[str, ...]) -> Decimal | None:
    return None if any(fields.get(name) is None for name in names) else sum((fields[name] for name in names), Decimal(0))


def _check_limit(checks: list, name: str, amount: Decimal | None, maximum: Decimal | None) -> None:
    difference = None if amount is None or maximum is None else amount - maximum
    checks.append({"id": name, "status": "insufficient_data" if difference is None else
                   "ok" if difference <= _TOLERANCE else "mismatch",
                   "difference": None if difference is None else format(difference, "f")})


def _derive(section: str, fields: dict, sources: dict) -> tuple[dict, list]:
    metrics: dict = {}
    checks: list = []
    if section == "balance_sheet":
        equity_sum = _sum_fields(fields, ("liabilities", "equity"))
        _check(checks, "assets_equal_liabilities_plus_equity", fields.get("assets"), equity_sum)
        _check(checks, "reported_liabilities_and_equity", fields.get("reported_liabilities_and_equity"), equity_sum)
        _check_limit(checks, "current_assets_within_assets", fields.get("current_assets"), fields.get("assets"))
        _check_limit(checks, "current_liabilities_within_liabilities", fields.get("current_liabilities"), fields.get("liabilities"))
        _check_limit(checks, "cash_within_current_assets", fields.get("cash_balance"), fields.get("current_assets"))
    elif section == "income_statement":
        expense_names = ("operating_expense_total", "interest_expense", "tax_expense")
        fields["total_expenses"] = _sum_fields(fields, expense_names)
        sources["total_expenses"] = [cell for name in expense_names for cell in sources.get(name, [])]
        operating_names = ("selling_expenses", "administrative_expenses", "exchange_loss")
        fields["operating_expenses"] = _sum_fields(fields, operating_names)
        sources["operating_expenses"] = [cell for name in operating_names for cell in sources.get(name, [])]
        _check(checks, "operating_expense_categories", fields.get("operating_expense_total"),
               _sum_fields(fields, ("cost_of_goods_sold", *operating_names)))
        profit = None
        if fields.get("revenue") is not None and fields["total_expenses"] is not None:
            profit = calculate_net_profit(fields["revenue"], fields["total_expenses"])
            metrics["net_profit"] = format(profit, "f")
        _check(checks, "reported_net_profit", fields.get("net_income"), profit)
    else:
        net = _sum_fields(fields, ("operating_cash_flow", "investing_cash_flow", "financing_cash_flow"))
        _check(checks, "reported_net_cash_flow", fields.get("reported_net_cash_flow"), net)
        closing = None if net is None or fields.get("opening_cash_including_restricted") is None else fields["opening_cash_including_restricted"] + net
        _check(checks, "cash_roll_forward", fields.get("closing_cash_including_restricted"), closing)
        if net is not None:
            metrics["net_cash_flow"] = format(net, "f")
        if fields.get("operating_cash_flow") is not None and fields.get("capital_expenditure") is not None:
            metrics["fcf"] = format(calculate_fcf(fields["operating_cash_flow"], fields["capital_expenditure"]), "f")
    return metrics, checks


def _extract_sheet(sheet) -> list[dict]:
    if (sheet.max_row or 0) > _MAX_STATEMENT_ROWS or (sheet.max_column or 0) > _MAX_COLUMNS:
        raise ExtractionError("Statement layout supports at most 256 rows and six columns")
    sheet.reset_dimensions()
    rows = list(sheet.iter_rows(max_row=_MAX_STATEMENT_ROWS + 1, max_col=_MAX_COLUMNS + 1))
    for row in rows:
        for cell in row:
            if cell.value is not None:
                if cell.row > _MAX_STATEMENT_ROWS or cell.column > _MAX_COLUMNS:
                    raise ExtractionError("Statement layout exceeds the supported range")
                if cell.data_type in {"f", "e"}:
                    raise ExtractionError(f"Cell {cell.coordinate}: formulas and Excel errors are not allowed; paste values")
    headers = [index for index, row in enumerate(rows) if isinstance(row[0].value, str) and
               _normalize(row[0].value) in {_normalize("Item"), _normalize("รายการ")}]
    if len(headers) != 4:
        raise ExtractionError("Expected balance sheet, income, cash flow, and equity table headers")
    records = []
    for section_index, section in enumerate(_LABELS):
        start, stop = headers[section_index], headers[section_index + 1]
        columns = [column for column in range(1, _MAX_COLUMNS) if isinstance(rows[start][column].value, str) and
                   _normalize(rows[start][column].value) not in {_normalize("หมายเหตุ"), "notes"}]
        if len(columns) != 2:
            raise ExtractionError("Each statement must contain exactly two reporting-period columns")
        aliases = {_normalize(label): field for field, labels in _LABELS[section].items() for label in labels}
        unit_notes = [str(row[0].value) for row in rows[max(0, start - 3):start] if row[0].value is not None]
        currency, scale = _units([*(str(rows[start][column].value) for column in columns), *unit_notes])
        for column in columns:
            fields = dict.fromkeys(_LABELS[section])
            raw_values = {}
            sources = {}
            seen = set()
            for row in rows[start + 1:stop]:
                field = aliases.get(_normalize(row[0].value)) if isinstance(row[0].value, str) else None
                if field is None:
                    continue
                if field in seen:
                    raise ExtractionError(f"Sheet {sheet.title}: duplicate statement total {field}")
                seen.add(field)
                fields[field], raw_values[field] = _amount(row[column], field, scale)
                sources[field] = [row[column].coordinate]
            period = _period(rows[start][column].value)
            metrics, checks = _derive(section, fields, sources)
            known = [value for value in fields.values() if value is not None]
            missing = [name for name, value in fields.items() if value is None]
            warnings = []
            if period["year"] is None:
                warnings.append("Reporting year is a placeholder; explicit period context is required.")
            if currency is None:
                warnings.append("Currency is not declared; explicit currency context is required.")
            if section == "cash_flow_statement":
                warnings.append("Cash totals include restricted cash; unrestricted reserves and CFADS are not inferred.")
            status = "invalid" if any(item["status"] == "mismatch" for item in checks) else (
                "empty_template" if known and not any(known) and period["year"] is None else
                "insufficient_data" if missing or currency is None or period["year"] is None else "ok")
            records.append({"sheet": sheet.title, "section": section, "column": get_column_letter(column + 1),
                            "period": period, "currency": currency, "sourceScale": str(scale),
                            "fields": {name: None if value is None else format(value, "f") for name, value in fields.items()},
                            "sourceValues": raw_values, "sourceCells": sources, "metrics": metrics,
                            "checks": checks, "status": status, "missingFields": missing, "warnings": warnings})
    return records


def extract_statement_workbook(content: bytes, filename: str) -> dict:
    if Path(filename).suffix.lower() != ".xlsx" or not content or len(content) > MAX_UPLOAD_BYTES:
        raise ExtractionError("Expected a non-empty .xlsx workbook no larger than 5 MiB")
    try:
        with ZipFile(BytesIO(content)) as archive:
            entries = archive.infolist()
            if len(entries) > 1000 or sum(item.file_size for item in entries) > MAX_EXPANDED_BYTES:
                raise ExtractionError("Workbook expanded size exceeds the import limit")
        workbook = load_workbook(BytesIO(content), read_only=True, data_only=False, keep_links=False)
    except ExtractionError:
        raise
    except Exception as exc:
        raise ExtractionError("Invalid or unreadable .xlsx workbook") from exc
    try:
        if len(workbook.sheetnames) > _MAX_SHEETS:
            raise ExtractionError("Workbook supports at most eight statement sheets")
        with localcontext() as context:
            context.prec = 50
            statements = [record for sheet in workbook for record in _extract_sheet(sheet)]
        status = "invalid" if any(record["status"] == "invalid" for record in statements) else "requires_context"
        return {"source": Path(filename).name, "status": status, "statements": statements,
                "grading": {"grade": None, "score": None, "status": "insufficient_data"},
                "warnings": ["Select statements for the same business, reporting period, and currency before grading.",
                             "Equity movement tables are not used as balance-sheet totals or income-statement profit."]}
    except (ExtractionError, ValidationError):
        raise
    except Exception as exc:
        raise ExtractionError("Invalid or unreadable multi-statement layout") from exc
    finally:
        workbook.close()


def extract_statement_file(path: str | Path = DEFAULT_TEMPLATE_PATH) -> dict:
    file_path = Path(path)
    with file_path.open("rb") as source:
        content = source.read(MAX_UPLOAD_BYTES + 1)
    return extract_statement_workbook(content, file_path.name)
