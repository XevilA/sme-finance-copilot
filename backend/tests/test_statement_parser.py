def content(book):
    stream = BytesIO()
    book.save(stream)
    book.close()
    return stream.getvalue()


def records(book):
    return extract_statement_workbook(content(book), "Financial_Statement_Translated.xlsx")


@pytest.mark.parametrize("thai", [False, True])
def test_extracts_period_columns_units_expenses_and_scoped_provenance(thai):
    result = records(fixture_book(thai=thai))
    assert result["status"] == "requires_context"
    assert result["grading"]["grade"] is None
    assert len(result["statements"]) == 6
    balance, _, income, _, cash, _ = result["statements"]
    assert balance["fields"]["assets"] == "100000"
    assert all(check["status"] == "ok" for check in balance["checks"])
    assert income["column"] == "C"
    assert income["period"]["year"] == 2019
    assert income["currency"] == "THB"
    assert income["fields"]["total_expenses"] == "6500"
    assert income["fields"]["operating_expenses"] == "2000"
    assert income["metrics"]["net_profit"] == "3500"
    assert income["sourceCells"]["total_expenses"] == ["C24", "C29", "C30"]
    assert income["fields"]["net_income"] != "99999"
    assert cash["currency"] == "USD"
    assert cash["sourceScale"] == "1000000"
    assert cash["period"]["periodEnd"] == "2019-09-28"
    assert cash["metrics"] == {"net_cash_flow": "15000000", "fcf": "18000000"}
    assert cash["fields"]["capital_expenditure"] == "12000000"
    assert cash["sourceValues"]["capital_expenditure"] == "-12"
    assert all(check["status"] == "ok" for check in cash["checks"])
    assert "cash_balance" not in cash["fields"]


@pytest.mark.parametrize("cell,value", [("B5", 100001), ("B8", 100001), ("B9", 60001), ("B10", 30001),
                                       ("C31", 3501), ("B52", 16), ("B53", 66)])
def test_reconciliation_failures_are_reported_as_invalid(cell, value):
    book = fixture_book()
    book.active[cell] = value
    result = records(book)
    assert result["status"] == "invalid"
    assert any(check["status"] == "mismatch" for record in result["statements"] for check in record["checks"])


def test_missing_dash_does_not_become_zero_or_change_complete_profit_calculation():
    book = fixture_book()
    book.active["C28"] = "-"
    income = records(book)["statements"][2]
    assert income["fields"]["exchange_loss"] is None
    assert income["fields"]["operating_expenses"] is None
    assert income["metrics"]["net_profit"] == "3500"
    assert income["status"] == "insufficient_data"


@pytest.mark.parametrize("cell,value", [("B5", "=1+1"), ("B5", "#DIV/0!"), ("B5", True), ("B5", -1)])
def test_rejects_formulas_errors_boolean_amounts_and_negative_assets(cell, value):
    book = fixture_book()
    book.active[cell] = value
    with pytest.raises(ExtractionError):
        records(book)


def test_rejects_duplicate_totals_and_currency_conflicts():
    for cell, value in [("A15", "Total Assets"), ("A44", "USD in millions and THB")]:
        book = fixture_book()
        book.active[cell] = value
        with pytest.raises(ExtractionError):
            records(book)


def test_placeholder_zero_balance_is_marked_as_template():
    book = fixture_book()
    book.active["B4"] = "Year 20xx (Baht)"
    for row in range(5, 12):
        book.active.cell(row, 2, 0)
    balance = records(book)["statements"][0]
    assert balance["status"] == "empty_template"
    assert balance["period"]["year"] is None


def test_existing_financial_input_parser_rejects_unsafe_combined_analysis():
    with pytest.raises(ExtractionError, match="consistent business, period, and currency"):
        parse_excel(content(fixture_book()), "statement.xlsx")


def test_rejects_expanded_archives_and_oversized_layouts(monkeypatch):
    book = fixture_book()
    book.active["A257"] = "Overflow"
    with pytest.raises(ExtractionError, match="256 rows"):
        records(book)
    monkeypatch.setattr(statement_parser, "MAX_EXPANDED_BYTES", 1)
    with pytest.raises(ExtractionError, match="expanded size"):
        records(fixture_book())
